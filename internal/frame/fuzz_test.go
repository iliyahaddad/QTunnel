func FuzzDecode(f *testing.F) {
	testFrames := [][]byte{
		// CONNECT frame
		{0x01, 0x00, 0x12, 0x09, 0x65, 0x78, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x2e, 0x63, 0x6f, 0x6d, 0x01, 0xbb, 0x00},
		// DATA frame
		{0x04, 0x01, 0x05, 0x68, 0x65, 0x6c, 0x6c, 0x6f},
		// CLOSE frame
		{0x05, 0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
		// PING frame
		{0x06, 0x02, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x49, 0x96, 0x02, 0xd2, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08},
		// AUTH frame
		{0x08, 0x00, 0x0c, 0x74, 0x65, 0x73, 0x74, 0x2d, 0x74, 0x6f, 0x6b, 0x65, 0x6e},
		// WINDOW_UPDATE frame
		{0x0b, 0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00},
		// GOAWAY frame
		{0x0c, 0x00, 0x12, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x64, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0b, 0x67, 0x72, 0x61, 0x63, 0x65, 0x66, 0x75, 0x6c, 0x20, 0x73, 0x68, 0x75, 0x74, 0x64, 0x6f, 0x77, 0x6e},
	}

	for _, frameData := range testFrames {
		f.Add(frameData)
	}

	f.Fuzz(func(t *testing.T, data []byte) {
		_, _ = Decode(data)
	})
}

